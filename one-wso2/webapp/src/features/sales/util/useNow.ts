import { useEffect, useState } from "react";

/**
 * The current time in ms, read once on mount and then every `everyMs`.
 *
 * A clock as state rather than Date.now() in render: render must be pure, and a value
 * that moves on its own keeps a tab left open from showing "today" a day late.
 */
export function useNow(everyMs = 60_000): number {
  const [now, setNow] = useState(() => Date.now());
  useEffect(() => {
    const id = setInterval(() => setNow(Date.now()), everyMs);
    return () => clearInterval(id);
  }, [everyMs]);
  return now;
}
